//! Recorded `sinf`/`cosf` inputs of the smog crowd generator, so the crowd goldens do not depend
//! on the host's `libm`.
//!
//! # Responsibility
//! Holds [`CROWD_TRIG_BITS`]: for each bubble index `i` in `0..600`, the `f32` bits of the four
//! trig values the crowd branch of `client::smog::generate_bouncing_bubbles` computes:
//! `(i as f32 * GOLDEN_RATIO).sin()`, `(i as f32 * PI).sin()`, `(i as f32 * 2.399_963_1).cos()`
//! and `(i as f32 * 2.399_963_1).sin()`, in that order.
//!
//! # Fit
//! Included by `smog_golden_tests.rs` with `#[path]`. Its `crowd_lattice` replicates the
//! generator with these values in place of the trig calls, so the 24-, 48-, 400- and 600-bubble
//! crowd scenarios start from the same bits on every host. The rows do not depend on the crowd
//! size, so one table serves every crowd.
//!
//! # Invariants
//! - Recorded on this project's development server (Debian 13, glibc 2.41, `x86_64`, rustc 1.99.0)
//!   at commit `3f57fec`, by a temporary printer test that was deleted before committing.
//! - `crowd_trig_table_matches_host` checks every entry is within 2 ulps of the running host's
//!   value, and `crowd_generator_matches_lattice` pins the replica to the generator bit for bit.
//! - Never edited by hand: a changed generator expression means re-recording the whole table.

